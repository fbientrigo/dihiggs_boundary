def test_positivity_stability_alias_in_vendored_source():
    """Contract check on the exact vendored source being built:
    Constraints::check_positivity() and Constraints::check_stability() both
    return model.check_stability() in stock 2HDMC 1.8. This makes the alias
    visible; it deliberately does not rename or 'fix' anything.
    """
    with open(CONSTRAINTS_CPP, encoding="utf-8", errors="replace") as f:
        source = f.read()

    import re

    def body_of(function_name):
        pattern = (
            r"bool\s+Constraints::%s\s*\(\s*\)\s*\{(.*?)\}" % function_name
        )
        match = re.search(pattern, source, re.DOTALL)
        assert match, "cannot locate Constraints::%s in %s" % (
            function_name,
            CONSTRAINTS_CPP,
        )
        return match.group(1)

    positivity_body = body_of("check_positivity")
    stability_body = body_of("check_stability")
    assert "return model.check_stability();" in positivity_body
    assert "return model.check_stability();" in stability_body


def test_m2_reconstruction_invariant(expected_by_id):
    """M2_recomputed == m12_sq_derived / (sin(beta) * cos(beta)), and the
    evaluator's own relative reconstruction error stays below a frozen bound.
    """
    for pid, row in expected_by_id.items():
        if row["set_param_phys_ok"] != "1":
            continue
        beta = float(row["beta"])
        m12_sq_derived = float(row["m12_sq_derived"])
        m2_recomputed = float(row["M2_recomputed"])
        recomputed_here = m12_sq_derived / (math.sin(beta) * math.cos(beta))
        # Python libm may differ from the C++ libm by ~1 ULP in sin/cos.
        assert floats_match(m2_recomputed, recomputed_here, 1e-13, 0.0), (
            "golden %s: M2_recomputed=%r vs m12_sq_derived/(sb*cb)=%r"
            % (pid, m2_recomputed, recomputed_here)
        )
        rel_err = float(row["relative_M2_reconstruction_error"])
        assert rel_err < 1e-9, (
            "golden %s: relative_M2_reconstruction_error=%r above frozen 1e-9"
            % (pid, rel_err)
        )


def test_ctau_lifetime_invariant(expected_by_id):
    """ctau_mm_H2 == hbar*c[GeV*mm] / total_width_H2[GeV], with the constant
    1.973269804e-13 GeV*mm frozen in src/evaluate_point.cpp and mirrored by
    dhb.contracts.HBAR_C_GEV_MM. 17-digit serialization round-trips exactly,
    so this division reproduces at Float64 precision.
    """
    assert HBAR_C_GEV_MM == contracts.HBAR_C_GEV_MM
    for pid, row in expected_by_id.items():
        width = float(row["total_width_H2"])
        ctau = float(row["ctau_mm_H2"])
        if not (math.isfinite(width) and width > 0.0):
            assert math.isnan(ctau), pid
            continue
        assert floats_match(ctau, HBAR_C_GEV_MM / width, 1e-15, 0.0), (
            "golden %s: ctau_mm_H2=%r vs hbar_c/width=%r"
            % (pid, ctau, HBAR_C_GEV_MM / width)
        )


