def test_lambda67_derived_policy_is_exact_and_rejects_zero_for_1em12():
    """Regression for the invalid 1e-11 absolute floor: lambda6_derived /
    lambda7_derived are pass-through values (G05 has lambda6 = 1e-12), so
    their policy must be exact, and an actual 0.0 must FAIL against an
    expected 1e-12 (and vice versa)."""
    for column in ("lambda6_derived", "lambda7_derived"):
        group, rel, abs_tol = field_tolerance(column)
        assert group == "exact"
        assert rel == 0.0 and abs_tol == 0.0
        assert floats_match(1e-12, 0.0, rel, abs_tol) is False
        assert floats_match(0.0, 1e-12, rel, abs_tol) is False
        assert floats_match(0.0, 0.0, rel, abs_tol) is True
        assert floats_match(1e-12, 1e-12, rel, abs_tol) is True


def test_lambda67_derived_pass_through_invariant(expected_by_id):
    """The vendored 2HDMC stores lambda6/lambda7 and returns them unmodified,
    so on every constructed row lambda{6,7}_derived must equal
    lambda{6,7}_input EXACTLY (an expected zero requires an actual zero), and
    on failed construction they must be NaN."""
    for pid, row in expected_by_id.items():
        for input_col, derived_col in (
            ("lambda6_input", "lambda6_derived"),
            ("lambda7_input", "lambda7_derived"),
        ):
            derived = float(row[derived_col])
            if row["set_param_phys_ok"] != "1":
                assert math.isnan(derived), (
                    "golden %s: %s must be NaN on failed construction, got %r"
                    % (pid, derived_col, row[derived_col])
                )
                continue
            passed_in = float(row[input_col])
            assert derived == passed_in, (
                "golden %s: %s=%r must exactly equal %s=%r (pass-through)"
                % (pid, derived_col, row[derived_col], input_col, row[input_col])
            )
            if passed_in == 0.0:
                assert derived == 0.0


