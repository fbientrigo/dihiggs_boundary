@needs_binary
def test_serial_vs_two_shard_merge(tmp_path):
    """The repository's supported sharded path (scripts/split_point_csv.py +
    scripts/merge_shard_outputs.py) must reproduce the serial scientific rows
    exactly, in the same stable point order."""
    serial_csv = tmp_path / "serial.csv"
    run_evaluate_point(INPUT_CSV, serial_csv)

    shards_dir = tmp_path / "shards"
    subprocess.run(
        [
            sys.executable,
            os.path.join(REPO_ROOT, "scripts", "split_point_csv.py"),
            "--input",
            INPUT_CSV,
            "--outdir",
            str(shards_dir),
            "--n-shards",
            "2",
        ],
        check=True,
        capture_output=True,
    )
    for shard in sorted(os.listdir(shards_dir)):
        shard_dir = shards_dir / shard
        if not shard_dir.is_dir():
            continue
        run_evaluate_point(shard_dir / "points.csv", shard_dir / "evaluate_point.csv")

    merged_csv = tmp_path / "merged.csv"
    subprocess.run(
        [
            sys.executable,
            os.path.join(REPO_ROOT, "scripts", "merge_shard_outputs.py"),
            "--shards-dir",
            str(shards_dir),
            "--output",
            str(merged_csv),
        ],
        check=True,
        capture_output=True,
    )

    serial_header, serial_rows = read_csv(str(serial_csv))
    merged_header, merged_rows = read_csv(str(merged_csv))
    assert merged_header == serial_header
    assert merged_rows == serial_rows, (
        "merged shard output must equal the serial output field-for-field"
    )
