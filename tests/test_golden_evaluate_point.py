def test_synthetic_theory_ok_boolean_logic():
    """SYNTHETIC (non-physics): pure boolean-combination check of the
    documented acceptance expression

        theory_ok = set_param_phys_ok && triple_ok && stability_ok && width_ok

    The current stock 2HDMC cannot produce a physical point with triple_ok=1
    and stability_ok=0 (positivity and stability are aliased), so this
    combination is exercised only as a synthetic record here to prove the
    expression would still veto it.
    """

    def theory_ok(set_ok, triple, stability, width_ok):
        return set_ok and triple and stability and width_ok

    synthetic_record = dict(set_ok=True, triple=True, stability=False, width_ok=True)
    assert theory_ok(**synthetic_record) is False
    assert theory_ok(True, True, True, True) is True
    assert theory_ok(False, True, True, True) is False
    assert theory_ok(True, True, True, False) is False


