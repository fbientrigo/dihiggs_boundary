def test_floats_match_non_finite_handling():
    """Non-finite classification precedes the tolerance formula: infinities
    match only same-signed infinities; infinity-vs-finite fails in both
    directions; NaN matches only NaN."""
    inf = math.inf
    rel, abs_tol = 1e-10, 1e-24  # the widest ("loop") policy in this suite
    assert floats_match(1.0, inf, rel, abs_tol) is False
    assert floats_match(inf, 1.0, rel, abs_tol) is False
    assert floats_match(inf, inf, rel, abs_tol) is True
    assert floats_match(inf, -inf, rel, abs_tol) is False
    assert floats_match(-inf, -inf, rel, abs_tol) is True
    assert floats_match(-inf, inf, rel, abs_tol) is False
    assert floats_match(1.0, -inf, rel, abs_tol) is False
    assert floats_match(-inf, 1.0, rel, abs_tol) is False
    # NaN-mask contract: NaN pairs pass; NaN against anything else fails.
    nan = math.nan
    assert floats_match(nan, nan, rel, abs_tol) is True
    assert floats_match(nan, 1.0, rel, abs_tol) is False
    assert floats_match(1.0, nan, rel, abs_tol) is False
    assert floats_match(nan, inf, rel, abs_tol) is False
    assert floats_match(inf, nan, rel, abs_tol) is False
    # The same classification holds under an exact (0, 0) policy.
    assert floats_match(inf, inf, 0.0, 0.0) is True
    assert floats_match(inf, -inf, 0.0, 0.0) is False


def test_row_length_guard_detects_truncated_and_overlong_rows():
    """Removing a trailing field (or appending a spurious one) must be
    detected by assert_row_lengths, never silently absorbed by zip()."""
    header = ["point_id", "a", "b"]
    assert_row_lengths(header, [["p1", "1", "2"]], "expected")  # exact: passes

    truncated = [["p1", "1"]]  # trailing field removed
    with pytest.raises(AssertionError) as excinfo:
        assert_row_lengths(header, truncated, "actual")
    message = str(excinfo.value)
    assert "actual" in message
    assert "p1" in message
    assert "has 2 fields" in message
    assert "header has 3" in message

    overlong = [["p2", "1", "2", "3"]]
    with pytest.raises(AssertionError) as excinfo:
        assert_row_lengths(header, overlong, "expected")
    message = str(excinfo.value)
    assert "expected" in message
    assert "p2" in message
    assert "has 4 fields" in message
