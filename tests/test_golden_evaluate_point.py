def field_tolerance(column):
    """Return (group_name, rel, abs) for a float column."""
    for name, spec in FIELD_GROUPS.items():
        if column in spec["fields"]:
            return name, spec["rel"], spec["abs"]
    return "loop", LOOP_REL, LOOP_ABS


def floats_match(a, b, rel, abs_tol):
    """Compare expected `a` against actual `b` under (rel, abs_tol).

    Non-finite values are classified BEFORE any tolerance arithmetic, so no
    NaN or infinity ever enters the tolerance formula:
      - NaN matches only NaN (the expected NaN-mask contract);
      - an infinity matches only an infinity of the same sign;
      - any infinity-vs-finite (either direction) fails;
      - only finite-vs-finite reaches the tolerance comparison.
    """
    if math.isnan(a) or math.isnan(b):
        return math.isnan(a) and math.isnan(b)
    if math.isinf(a) or math.isinf(b):
        return a == b
    if a == b:
        return True
    if rel == 0.0 and abs_tol == 0.0:
        return False
    return abs(a - b) <= max(rel * max(abs(a), abs(b)), abs_tol)


def assert_row_lengths(header, rows, kind):
    """Assert every row has exactly len(header) fields.

    Guards the zip()-based field comparisons, which would otherwise silently
    drop trailing fields on a truncated row (zip stops at the shorter side).
    `kind` labels the side being checked ("expected" or "actual").
    """
    for idx, row in enumerate(rows):
        pid = row[0] if row else "<empty row>"
        assert len(row) == len(header), (
            "%s row %d (point_id=%s): has %d fields, header has %d"
            % (kind, idx, pid, len(row), len(header))
        )


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = list(reader)
    return header, rows


