@needs_binary
def test_regenerated_output_matches_golden(tmp_path, golden_expected):
    """Re-run the compiled evaluator on the committed golden input and compare
    against the frozen expected.csv with the per-field policy above."""
    out_csv = tmp_path / "evaluate_point.csv"
    run_evaluate_point(INPUT_CSV, out_csv)

    exp_header, exp_rows = golden_expected
    got_header, got_rows = read_csv(str(out_csv))

    assert got_header == exp_header, "output header drifted"
    assert len(got_rows) == len(exp_rows), "row cardinality drifted"
    # zip() below stops at the shorter side, so truncated/overlong rows must
    # be rejected explicitly before any field-by-field comparison.
    assert_row_lengths(exp_header, exp_rows, "expected")
    assert_row_lengths(exp_header, got_rows, "actual")

    failures = []
    for exp_row, got_row in zip(exp_rows, got_rows):
        pid = exp_row[0]
        for col, exp_text, got_text in zip(exp_header, exp_row, got_row):
            if col in STRING_EXACT_COLUMNS or col in INT_EXACT_COLUMNS:
                if exp_text != got_text:
                    failures.append(
                        "%s.%s: expected %r got %r (exact)" % (pid, col, exp_text, got_text)
                    )
                continue
            exp_val = float(exp_text)
            got_val = float(got_text)
            group, rel, abs_tol = field_tolerance(col)
            if not floats_match(exp_val, got_val, rel, abs_tol):
                failures.append(
                    "%s.%s: expected %r got %r (group=%s rel=%g abs=%g)"
                    % (pid, col, exp_text, got_text, group, rel, abs_tol)
                )
    assert not failures, "golden mismatch:\n  " + "\n  ".join(failures)


